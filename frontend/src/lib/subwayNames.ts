function normalizeStationName(value: string): string {
  return value
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s.·ㆍ・-]/g, "")
    .replace(/(station|stn\.|駅|역)$/i, "");
}

function normalizeSearchValue(value: string): string {
  return value
    .normalize("NFKC")
    .toLowerCase()
    .replace(/[\s.·ㆍ・-]/g, "");
}

export function findSubwayStationName(
  nameKo: string,
  line: number,
): SubwayStationName | null {
  const normalized = normalizeStationName(nameKo);
  return (
    SUBWAY_STATION_NAMES.find(
      (station) =>
        station.line === line &&
        normalizeStationName(station.nameKo) === normalized,
    ) ?? null
  );
}

export function localizeSubwayStationName(
  nameKo: string,
  line: number,
  lang: SubwayNameLanguage,
): string {
  const station = findSubwayStationName(nameKo, line);
  if (!station) return lang === "ko" ? `${nameKo}역` : nameKo;
  if (lang === "ko") return `${station.nameKo}역`;
  if (lang === "ja") {
    return station.nameJa.endsWith("駅")
      ? station.nameJa
      : `${station.nameJa}駅`;
  }
  return /station$/i.test(station.nameEn)
    ? station.nameEn
    : `${station.nameEn} Station`;
}

export function matchesSubwayStationName(
  nameKo: string,
  line: number,
  query: string,
): boolean {
  const station = findSubwayStationName(nameKo, line);
  const normalizedQuery = normalizeSearchValue(query);
  if (!normalizedQuery) return true;
  const candidates = station
    ? [
        station.nameKo,
        `${station.nameKo}역`,
        station.nameEn,
        /station$/i.test(station.nameEn)
          ? station.nameEn
          : `${station.nameEn} Station`,
        station.romanized,
        station.nameJa,
        station.nameJa.endsWith("駅")
          ? station.nameJa
          : `${station.nameJa}駅`,
        station.nameZhHans,
        station.nameZhHant,
      ]
    : [nameKo];
  return candidates.some((candidate) =>
    normalizeSearchValue(candidate).includes(normalizedQuery),
  );
}
